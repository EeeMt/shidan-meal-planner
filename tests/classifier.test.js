// ============ 4. 灰区配置与兜底 ============
// grayMeat: 高汤/猪油/蚝油等动物性调味默认不计荤，置 true 后计入
const grayDish = dish('菌菇高汤锅', '素菜', [['香菇'], ['高汤'], ['猪油']]);
ok('灰区·默认不计荤', !C.classifyDish(grayDish).isMeat && !C.classifyDish(grayDish).hasProtein);
ok('灰区·grayMeat 计入荤', C.classifyDish(grayDish, { grayMeat: true }).isMeat);
// 没有配料时回退到分类
const noIng = dish('自定义红烧肉', '荤菜', []);
ok('兜底·无配料按分类', C.classifyDish(noIng).isMeat && C.classifyDish(noIng).hasProtein);
const noIngVeg = dish('自定义时蔬', '素菜', []);
ok('兜底·素菜无配料', !C.classifyDish(noIngVeg).isMeat && !C.classifyDish(noIngVeg).hasProtein);
// 可选配料不参与（干煸四季豆场景）
const optMeat = dish('豆角肉末', '素菜', [['豆角'], ['猪肉末', true]]);
ok('可选·肉末可选不算荤', !C.classifyDish(optMeat).isMeat);
ok('可选·肉末改为必备算荤', C.classifyDish(dish('豆角肉末', '素菜', [['豆角'], ['猪肉末']])).isMeat);

